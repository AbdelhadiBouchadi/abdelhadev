// Writes src/components/brand/wordmark-paths.ts from brand/wordmark-animated.svg, formatted with
// the repo's Prettier config so CI can check it is fresh with git diff --exit-code.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import * as prettier from "prettier";

const root = resolve(import.meta.dirname, "..");
const source = resolve(root, "brand/wordmark-animated.svg");
const target = resolve(root, "src/components/brand/wordmark-paths.ts");

/** Drops trailing zeros too. */
export function roundPath(d) {
  return d.replace(/-?\d*\.?\d+(?:e-?\d+)?/gi, (n) => String(Number(Number(n).toFixed(2))));
}

/** In order of their gN id. */
export function parseWordmark(svg) {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (!viewBox) throw new Error("wordmark-animated.svg has no viewBox");
  const letters = [...svg.matchAll(/<path\s+id="g(\d+)"\s+d="([^"]+)"/g)]
    .map((m) => ({ index: Number(m[1]), d: roundPath(m[2]) }))
    .sort((a, b) => a.index - b.index);
  if (letters.length === 0) throw new Error("wordmark-animated.svg has no letter paths");
  letters.forEach((l, i) => {
    if (l.index !== i) throw new Error(`Letter paths are not contiguous at g${i}`);
  });
  return { viewBox: roundPath(viewBox), paths: letters.map((l) => l.d) };
}

async function main() {
  const { viewBox, paths } = parseWordmark(readFileSync(source, "utf8"));
  const code = `// Generated by scripts/build-brand-paths.mjs from brand/wordmark-animated.svg. Do not edit.
// Regenerate with: pnpm brand:paths

export const WORDMARK_VIEWBOX = ${JSON.stringify(viewBox)};

/** One path per letter of "Abdelhadev", in reading order. */
export const WORDMARK_PATHS: readonly string[] = ${JSON.stringify(paths)};
`;
  const options = (await prettier.resolveConfig(target)) ?? {};
  const formatted = await prettier.format(code, {
    ...options,
    filepath: target,
  });
  writeFileSync(target, formatted);
  console.log(`wordmark-paths.ts: ${paths.length} letters, viewBox ${viewBox}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
